package manifests

import (
	"context"

	"github.com/go-openapi/swag/conv"
	"github.com/pkg/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"sigs.k8s.io/yaml"

	"github.com/openshift/appliance/pkg/asset/config"
	"github.com/openshift/installer/pkg/asset"
	agenttypes "github.com/openshift/installer/pkg/types/agent"
)

const agentConfigFilename = "agent-config.yaml"

// AgentConfig generates the agent-config.yaml for the agent installer.
type AgentConfig struct {
	File   *asset.File
	Config *agenttypes.Config
}

var _ asset.WritableAsset = (*AgentConfig)(nil)

// Name returns a human friendly name for the asset.
func (*AgentConfig) Name() string {
	return "Agent Config"
}

// Dependencies returns all of the dependencies directly needed to generate the asset.
func (*AgentConfig) Dependencies() []asset.Asset {
	return []asset.Asset{
		&config.ApplianceConfig{},
	}
}

// Generate generates the agent-config.yaml when RendezvousIP is set.
func (a *AgentConfig) Generate(_ context.Context, dependencies asset.Parents) error {
	applianceConfig := &config.ApplianceConfig{}
	dependencies.Get(applianceConfig)

	if applianceConfig.Config.RendezvousIP == nil {
		return nil
	}

	agentCfg := &agenttypes.Config{
		TypeMeta: metav1.TypeMeta{
			APIVersion: agenttypes.AgentConfigVersion,
			Kind:       "AgentConfig",
		},
		RendezvousIP: conv.Value(applianceConfig.Config.RendezvousIP),
	}
	a.Config = agentCfg

	data, err := yaml.Marshal(agentCfg)
	if err != nil {
		return errors.Wrap(err, "failed to marshal agent config")
	}

	a.File = &asset.File{
		Filename: agentConfigFilename,
		Data:     data,
	}
	return nil
}

// Files returns the files generated by the asset.
func (a *AgentConfig) Files() []*asset.File {
	if a.File != nil {
		return []*asset.File{a.File}
	}
	return []*asset.File{}
}

// Load currently does nothing.
func (a *AgentConfig) Load(_ asset.FileFetcher) (bool, error) {
	return false, nil
}
