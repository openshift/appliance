package manifests

import (
	"context"
	"fmt"
	"path/filepath"

	"github.com/pkg/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"sigs.k8s.io/yaml"

	"github.com/openshift/appliance/pkg/asset/config"
	aiv1beta1 "github.com/openshift/assisted-service/api/v1beta1"
	"github.com/openshift/installer/pkg/asset"
)

const (
	nmStateConfigAPIVersion = "agent-install.openshift.io/v1beta1"
	nmStateConfigKind       = "NMStateConfig"
)

var (
	nmStateConfigFilename = filepath.Join(clusterManifestDir, "nmstateconfig.yaml")
)

// NMStateConfig generates the nmstateconfig.yaml file.
type NMStateConfig struct {
	File *asset.File
}

var _ asset.WritableAsset = (*NMStateConfig)(nil)

// Name returns a human friendly name for the asset.
func (*NMStateConfig) Name() string {
	return "NMState Config"
}

// Dependencies returns all of the dependencies directly needed to generate
// the asset.
func (*NMStateConfig) Dependencies() []asset.Asset {
	return []asset.Asset{
		&config.ApplianceConfig{},
	}
}

// Generate generates the NMStateConfig manifest.
func (n *NMStateConfig) Generate(_ context.Context, dependencies asset.Parents) error {
	applianceConfig := &config.ApplianceConfig{}
	dependencies.Get(applianceConfig)

	if len(applianceConfig.Config.NetworkConfig) == 0 {
		return nil
	}

	var data string
	for i, entry := range applianceConfig.Config.NetworkConfig {
		interfaces := make([]*aiv1beta1.Interface, len(entry.Interfaces))
		for j, iface := range entry.Interfaces {
			interfaces[j] = &aiv1beta1.Interface{
				Name:       iface.Name,
				MacAddress: iface.MacAddress,
			}
		}

		nmStateConfig := aiv1beta1.NMStateConfig{
			TypeMeta: metav1.TypeMeta{
				Kind:       nmStateConfigKind,
				APIVersion: nmStateConfigAPIVersion,
			},
			ObjectMeta: metav1.ObjectMeta{
				Name:      fmt.Sprintf("nmstate-%d", i),
				Namespace: "",
				Labels: map[string]string{
					"infraenvs.agent-install.openshift.io": infraEnvName,
				},
			},
			Spec: aiv1beta1.NMStateConfigSpec{
				Interfaces: interfaces,
				NetConfig: aiv1beta1.NetConfig{
					Raw: aiv1beta1.RawNetConfig(entry.Config),
				},
			},
		}

		nmStateConfigData, err := yaml.Marshal(nmStateConfig)
		if err != nil {
			return errors.Wrap(err, "failed to marshal NMStateConfig")
		}
		data = fmt.Sprint(data, fmt.Sprint(string(nmStateConfigData), "---\n"))
	}

	n.File = &asset.File{
		Filename: nmStateConfigFilename,
		Data:     []byte(data),
	}

	return nil
}

// Files returns the files generated by the asset.
func (n *NMStateConfig) Files() []*asset.File {
	if n.File != nil {
		return []*asset.File{n.File}
	}
	return []*asset.File{}
}

// Load returns nmstateconfig asset from the disk.
func (n *NMStateConfig) Load(f asset.FileFetcher) (bool, error) {
	return false, nil
}
